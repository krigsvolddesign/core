import {readFile,writeFile} from 'node:fs/promises';
const core=['theme','foundation','typography','components','layout','patterns','forms','source-profile'];
const reference=['shell','documents','examples','examples-family','components','scientific'];
const files=[...core.map(name=>`dist/${name}.css`),...reference.map(name=>`styles/reference/${name}.css`),'styles/dashboards.css','styles/dashboard-controls.css','styles/website.css'];
const css=await Promise.all(files.map(async file=>{
 const css=await readFile(file,'utf8');
 // The captured shell is retained for archive identity. Its search field used
 // a separate control definition; the live reference inherits Core controls.
 return file==='styles/reference/shell.css'?css.replace(/\.site-search-input\s*\{[^}]*\}/g,''):css;
}));
await writeFile('dist/krigsvold.css','/* Generated by Core. Astro and Jekyll consume these identical bytes. */\n'+css.join('\n'));
await writeFile('dist/dashboards.css',await readFile('styles/dashboards.css','utf8')+'\n'+await readFile('styles/dashboard-controls.css','utf8'));
for(const name of ['fonts','shell'])await writeFile(`dist/reference-${name}.css`,await readFile(`styles/reference/${name}.css`));

// React adapters are optional; the canonical krigsvold.css bytes remain shared.
await writeFile("dist/react.css", "@import './full.css';\n" + await readFile("styles/react.css", "utf8"));
await writeFile("dist/react-reference.css", await readFile("styles/reference/react.css", "utf8"));
